/** Translate a key, filling {params}; falls back to English for a missing translation. */
export function t(lang: LangCode, key: StringKey, params: Record<string, string | number> = {}): string {
  let s = STRINGS[lang]?.[key] ?? STRINGS_EN[key];
  for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Format rupees the Indian way (1,23,456) without depending on the runtime's ICU data. */
export function inr(n: number): string {
  const s = Math.round(n).toString();
  if (s.length <= 3) return `₹${s}`;
  const last3 = s.slice(-3);
  const rest = s.slice(0, -3).replace(/\B(?=(\d{2})+(?!\d))/g, ",");
  return `₹${rest},${last3}`;
}

