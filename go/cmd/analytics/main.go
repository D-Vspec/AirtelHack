// Command analytics renders the leads.v_* views into docs/analytics.md.
//
//	go run ./cmd/analytics -out ../docs/analytics.md
package main

import (
	"context"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/jackc/pgx/v5"

	"udyam/pkg/config"
)

var sections = []struct{ title, note, sql string }{
	{"Funnel by stage", "A lead counts at a stage if it has that stage's date.",
		`SELECT stage, leads, pct_of_previous, pct_of_leads FROM leads.v_funnel ORDER BY step`},
	{"Performance by segment", "CAC = all acquisition spend in the group / activations. Bundle value, churn and NPS are over activated leads.",
		`SELECT value AS segment, leads, activated, conversion_pct, cac_inr, avg_monthly_bundle_inr, churn_pct, avg_nps
		 FROM leads.v_segment_perf WHERE dimension = 'segment' ORDER BY conversion_pct DESC`},
	{"Performance by source", "",
		`SELECT value AS source, leads, activated, conversion_pct, cac_inr, avg_monthly_bundle_inr, churn_pct, avg_nps
		 FROM leads.v_segment_perf WHERE dimension = 'source' ORDER BY conversion_pct DESC`},
	{"Drop reasons by bucket", "fixable_by_digital = losses a self-serve journey removes (visits, quote speed/clarity, paperwork, signatory). before_first_contact = never reached the owner. out_of_scope = fulfilment, lock-in, intent.",
		`SELECT bucket, sum(leads) AS leads, sum(pct_of_drops) AS pct_of_drops FROM leads.v_drop_reasons GROUP BY bucket ORDER BY 2 DESC`},
	{"Drop reasons", "",
		`SELECT drop_reason, bucket, leads, pct_of_drops FROM leads.v_drop_reasons ORDER BY leads DESC`},
}

func main() {
	out := flag.String("out", "../docs/analytics.md", "output markdown file")
	flag.Parse()
	ctx := context.Background()
	conn, err := pgx.Connect(ctx, config.String("DATABASE_URL", "postgres://udyam:udyam@localhost:5432/udyam?sslmode=disable"))
	if err != nil {
		fail(err)
	}
	defer conn.Close(ctx)

	var b strings.Builder
	b.WriteString("# Lead analytics\n\nGenerated by `make seed` (go/cmd/analytics) from the leads.v_funnel, leads.v_segment_perf and leads.v_drop_reasons views over data/smb_leads.csv. Do not edit by hand.\n")
	for _, s := range sections {
		fmt.Fprintf(&b, "\n## %s\n\n", s.title)
		if s.note != "" {
			b.WriteString(s.note + "\n\n")
		}
		if err := table(ctx, conn, &b, s.sql); err != nil {
			fail(fmt.Errorf("%s: %w", s.title, err))
		}
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fail(err)
	}
	fmt.Println("wrote", *out)
}

// table renders any query as a markdown table, using Postgres' own text formatting.
func table(ctx context.Context, conn *pgx.Conn, b *strings.Builder, sql string) error {
	rows, err := conn.Query(ctx, sql, pgx.QueryExecModeSimpleProtocol)
	if err != nil {
		return err
	}
	defer rows.Close()
	var cols []string
	for _, f := range rows.FieldDescriptions() {
		cols = append(cols, f.Name)
	}
	fmt.Fprintf(b, "| %s |\n|%s\n", strings.Join(cols, " | "), strings.Repeat("---|", len(cols)))
	for rows.Next() {
		cells := make([]string, len(cols))
		for i, v := range rows.RawValues() {
			cells[i] = string(v)
		}
		fmt.Fprintf(b, "| %s |\n", strings.Join(cells, " | "))
	}
	return rows.Err()
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "analytics:", err)
	os.Exit(1)
}
