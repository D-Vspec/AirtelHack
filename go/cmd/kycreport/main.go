// Command kycreport runs the KYC pipeline on the 12 specimen applicants and writes
// docs/kyc-crosscheck.md: every field on every document compared with the other documents and the
// registries, including fields the pipeline deliberately does not act on (dates, activity).
//
//	cd go && go run ./cmd/kycreport -data ../data -out ../docs/kyc-crosscheck.md
package main

import (
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"image"
	_ "image/png"
	"os"
	"regexp"
	"sort"
	"strings"
	"time"

	"udyam/pkg/kyc"
	"udyam/pkg/logx"
	"udyam/pkg/registry"
)

func main() {
	data := flag.String("data", "../data", "data directory")
	out := flag.String("out", "../docs/kyc-crosscheck.md", "output markdown")
	flag.Parse()

	var exp struct {
		ReferenceDate string `json:"referenceDate"`
		Applicants    map[string]struct {
			FinalRoute string   `json:"finalRoute"`
			Codes      []string `json:"codes"`
		} `json:"applicants"`
	}
	b, err := os.ReadFile(*data + "/kyc_expected.json")
	must(err)
	must(json.Unmarshal(b, &exp))
	g, u, err := registry.LoadCSV(*data+"/mock_gstin_registry.csv", *data+"/mock_udyam_registry.csv")
	must(err)
	ref, _ := time.Parse(time.DateOnly, exp.ReferenceDate)
	c := kyc.NewChecker(kyc.IndexRegistry{G: g, U: u}, kyc.Tesseract, ref)

	ids := make([]string, 0, len(exp.Applicants))
	for id := range exp.Applicants {
		ids = append(ids, id)
	}
	sort.Strings(ids)

	var w strings.Builder
	fmt.Fprintf(&w, "# KYC cross-check, all 12 applicants\n\nGenerated by `cd go && go run ./cmd/kycreport` from the pipeline's own OCR reads (go/pkg/kyc) and the registry CSVs. Reference date %s. Identifiers are masked.\n\n", exp.ReferenceDate)
	w.WriteString("Legend: ✓ agrees, ✗ differs, - not available (document missing or unreadable). **Acted on** columns feed findings; **noted** columns are compared but do not produce findings (see Decisions below).\n\n")
	w.WriteString("## Verdicts\n\n| ID | route | codes | expected route | expected codes | match |\n|---|---|---|---|---|---|\n")

	type row struct {
		id    string
		cells []string
		notes []string
	}
	var rows []row
	for _, id := range ids {
		docs := map[string]image.Image{}
		for _, d := range kyc.RequiredDocs {
			f, err := os.Open(fmt.Sprintf("%s/kyc_documents/%s_%s.png", *data, id, d))
			if err != nil {
				continue
			}
			im, _, err := image.Decode(f)
			f.Close()
			must(err)
			docs[d] = im
		}
		res, err := c.Check(context.Background(), docs)
		must(err)
		var codes []string
		for _, f := range res.Findings {
			codes = append(codes, f.Code)
		}
		sort.Strings(codes)
		want := exp.Applicants[id]
		wc := append([]string(nil), want.Codes...)
		sort.Strings(wc)
		ok := res.Route == want.FinalRoute && strings.Join(codes, ",") == strings.Join(wc, ",")
		fmt.Fprintf(&w, "| %s | %s | %s | %s | %s | %s |\n", id, res.Route, strings.Join(codes, ", "), want.FinalRoute, strings.Join(wc, ", "), mark(ok))

		gst, udy, bill, sig := res.Fields[kyc.DocGST], res.Fields[kyc.DocUdyam], res.Fields[kyc.DocAddress], res.Fields[kyc.DocSignatory]
		rg, ru := res.GSTIN, res.Udyam
		r := row{id: id}
		cell := func(have bool, eq bool) string {
			if !have {
				return "-"
			}
			return mark(eq)
		}
		person, business := split(gst["legalName"])
		// Acted on
		gstinCell := "-"
		if g := kyc.GSTINText(gst["gstin"]); g != "" {
			switch {
			case rg == nil:
				gstinCell = "✗ not found"
			case rg.GSTIN == g:
				gstinCell = "✓ exact"
			default:
				gstinCell = "✓ OCR-corrected"
			}
		}
		r.cells = append(r.cells, gstinCell,
			cell(rg != nil, rg != nil && rg.Status == "Active")+status(rg),
			cell(gst != nil && rg != nil, rg != nil && eqName(gst["tradeName"], rg.TradeName)),
			cell(gst != nil && rg != nil, rg != nil && eqName(business, splitB(rg.LegalName)) && eqName(person, splitP(rg.LegalName))),
			cell(gst != nil && rg != nil, rg != nil && eqName(gst["constitution"], rg.Constitution)),
			cell(gst != nil && rg != nil, rg != nil && eqAddr(gst["address"], rg.Address)),
			udyamCell(udy, ru),
			cell(udy != nil && rg != nil, rg != nil && eqName(udy["enterpriseName"], rg.TradeName)),
			cell(udy != nil && rg != nil, rg != nil && strings.Contains(norm(rg.Address), norm(udy["city"])) && strings.Contains(norm(rg.Address), norm(udy["state"]))),
			cell(bill != nil && rg != nil, rg != nil && eqName(bill["billedTo"], rg.TradeName)),
			cell(bill != nil && rg != nil, rg != nil && eqAddr(bill["address"], rg.Address)),
			ageCell(bill, ref),
			cell(sig != nil && rg != nil, rg != nil && eqName(sig["forBusiness"], rg.TradeName)),
			signatoryCell(sig, rg),
			validCell(sig, ref),
		)
		// Noted only
		r.cells = append(r.cells,
			cell(gst != nil && rg != nil, rg != nil && kyc.Date(gst["dateOfLiability"]) == rg.RegistrationDate),
			cell(udy != nil && ru != nil, ru != nil && kyc.Date(udy["dateOfRegistration"]) == ru.DateOfRegistration),
			cell(udy != nil && ru != nil, ru != nil && eqName(udy["majorActivity"], ru.MajorActivity)),
		)
		if gst != nil && rg != nil && kyc.Date(gst["dateOfLiability"]) != rg.RegistrationDate {
			r.notes = append(r.notes, fmt.Sprintf("GST date of liability %s vs registry registration %s", kyc.Date(gst["dateOfLiability"]), rg.RegistrationDate))
		}
		if udy != nil && ru != nil {
			if d := kyc.Date(udy["dateOfRegistration"]); d != ru.DateOfRegistration {
				r.notes = append(r.notes, fmt.Sprintf("Udyam registration %s vs registry %s", d, ru.DateOfRegistration))
			}
			if !eqName(udy["majorActivity"], ru.MajorActivity) {
				r.notes = append(r.notes, fmt.Sprintf("Udyam activity %s vs registry %s", udy["majorActivity"], ru.MajorActivity))
			}
		}
		if sig != nil && rg != nil && rg.Constitution != "Proprietorship" {
			r.notes = append(r.notes, fmt.Sprintf("signatory %s (%s) for a %s: not verifiable, no partner/director list", sig["name"], sig["designation"], rg.Constitution))
		}
		if gst != nil && rg == nil {
			r.notes = append(r.notes, "certificate GSTIN "+logx.MaskID(kyc.GSTINText(gst["gstin"]))+" has no registry match")
		}
		rows = append(rows, r)
	}

	w.WriteString("\n## Field by field\n\n")
	head := []string{"GSTIN", "GST status", "trade name", "legal name + proprietor", "constitution", "GST address", "Udyam no.", "Udyam name", "Udyam city/state", "bill name", "bill address", "bill ≤90 days", "ID business", "signatory = proprietor", "ID valid", "*noted:* GST date", "*noted:* Udyam date", "*noted:* Udyam activity"}
	fmt.Fprintf(&w, "| ID | %s |\n|---|%s\n", strings.Join(head, " | "), strings.Repeat("---|", len(head)))
	for _, r := range rows {
		fmt.Fprintf(&w, "| %s | %s |\n", r.id, strings.Join(r.cells, " | "))
	}
	w.WriteString("\n## Discrepancies not acted on\n\n")
	for _, r := range rows {
		for _, n := range r.notes {
			fmt.Fprintf(&w, "- %s: %s\n", r.id, n)
		}
	}
	w.WriteString(`
## Decisions

- Registry comparisons use the GSTIN registry row the certificate resolves to (exact or OCR-corrected through checksum plus fuzzy match). Names tolerate small OCR slips (edit-distance ratio 0.85); addresses must agree on every digit (unit number, PIN) and tolerate letter slips and line wraps.
- GST date of liability matches the registry registration date on every readable certificate. Udyam registration dates differ from the Udyam registry for every applicant with a readable Udyam certificate, clean controls included, and the Udyam major activity differs for five. We treat the Udyam differences as generator noise and raise no findings: flagging them would send every applicant to manual review. To confirm with the organizers.
- Signatories of LLPs and companies cannot be verified: the mock registry lists no partners or directors. Designations such as "Owner" on an LLP are recorded here, not flagged. A partner/director source (MCA) would close this.
- K01's certificate GSTIN reads as I→T; K02 reads correctly only after deskew; K05 (tesseract 5.3 in the container) reads Z as 7; K03/K07/K08/K10 have O/0 or I/J confusions. All resolve through the registry's OCR-confusion classes.
`)
	must(os.WriteFile(*out, []byte(w.String()), 0o644))
	fmt.Println("wrote", *out)
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func mark(ok bool) string {
	if ok {
		return "✓"
	}
	return "✗"
}

func status(g *registry.GSTIN) string {
	if g == nil || g.Status == "Active" {
		return ""
	}
	return " " + g.Status
}

var propRe = regexp.MustCompile(`^(.*?)\s*\(\s*Prop\.?\s*(.*?)\s*\)\s*$`)

func split(legal string) (string, string) {
	if m := propRe.FindStringSubmatch(legal); m != nil {
		return m[1], m[2]
	}
	return "", legal
}
func splitP(l string) string { p, _ := split(l); return p }
func splitB(l string) string { _, b := split(l); return b }

func norm(s string) string {
	return strings.Map(func(r rune) rune {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			return r
		case r >= 'A' && r <= 'Z':
			return r + 32
		}
		return -1
	}, s)
}

func digits(s string) string { return regexp.MustCompile(`\D`).ReplaceAllString(s, "") }

// Report-level comparisons: exact after normalisation, so OCR slips show up here even when the
// pipeline's tolerant comparison accepts them.
func eqName(a, b string) bool { return norm(a) == norm(b) }
func eqAddr(a, b string) bool { return digits(a) == digits(b) && norm(a) == norm(b) }

func udyamCell(udy kyc.Fields, ru *registry.Udyam) string {
	switch {
	case udy == nil:
		return "-"
	case strings.TrimSpace(udy["udyamNumber"]) == "":
		return "✗ blank"
	case ru == nil:
		return "✗ not found"
	}
	return "✓"
}

func ageCell(bill kyc.Fields, ref time.Time) string {
	d, err := time.Parse(time.DateOnly, kyc.Date(bill["billDate"]))
	if err != nil {
		return "-"
	}
	days := int(ref.Sub(d).Hours() / 24)
	return fmt.Sprintf("%s %dd", mark(days <= 90), days)
}

func signatoryCell(sig kyc.Fields, rg *registry.GSTIN) string {
	if sig == nil || rg == nil {
		return "-"
	}
	if rg.Constitution != "Proprietorship" {
		return "n/a " + rg.Constitution
	}
	return mark(eqName(sig["name"], splitP(rg.LegalName)))
}

func validCell(sig kyc.Fields, ref time.Time) string {
	d, err := time.Parse(time.DateOnly, kyc.Date(sig["validTill"]))
	if err != nil {
		return "-"
	}
	return mark(!d.Before(ref))
}
