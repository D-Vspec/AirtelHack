#!/usr/bin/env python3
"""Generate docs/data-dictionary.md from the case CSVs (no hand-typed values)."""
import pandas as pd, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
out = ["# Data dictionary (generated by scripts/gen_data_dictionary.py)\n"]
for f in ["smb_leads", "product_catalogue", "mock_gstin_registry", "mock_udyam_registry"]:
    df = pd.read_csv(root / "data" / f"{f}.csv")
    out.append(f"\n## {f}.csv - {len(df)} rows\n\n| column | dtype | non-null | notes |\n|---|---|---|---|")
    for c in df.columns:
        s = df[c]; n = s.nunique()
        note = ", ".join(map(str, sorted(s.dropna().unique().tolist()))) if n <= 12 else f"{n} distinct, e.g. {s.dropna().iloc[0]}"
        out.append(f"| {c} | {s.dtype} | {s.notna().sum()} | {note[:160]} |")
(root / "docs" / "data-dictionary.md").write_text("\n".join(out) + "\n")
print("wrote docs/data-dictionary.md")
