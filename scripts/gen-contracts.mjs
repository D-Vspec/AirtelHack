#!/usr/bin/env node
// Generates Go and TS constants plus Kafka topic list from /contracts. Run: make contracts
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), "utf8"));
const write = (p, s) => { fs.mkdirSync(path.dirname(path.join(root, p)), { recursive: true }); fs.writeFileSync(path.join(root, p), s); console.log("wrote", p); };
const HDR = "// Code generated by scripts/gen-contracts.mjs from /contracts. DO NOT EDIT.\n";
const pascal = (s) => s.split(/[._]/).map((x) => x[0].toUpperCase() + x.slice(1)).join("");
const upper = (s) => s.replace(/\./g, "_").toUpperCase();

const { topics } = read("contracts/topics.json");
const kyc = read("contracts/kyc-findings.json");

// Kafka topics list for infra/kafka/create-topics.sh (name:partitions)
write("infra/kafka/topics.txt", topics.map((t) => `${t.name}:${t.partitions}`).join("\n") + "\n");

// Go topics
write("go/pkg/events/topics_gen.go",
  HDR + "package events\n\n// Topic names. Keep in sync via `make contracts`.\nconst (\n" +
  topics.map((t) => `\tTopic${pascal(t.name)} = "${t.name}"`).join("\n") +
  "\n)\n\n// AllTopics lists every topic.\nvar AllTopics = []string{\n" +
  topics.map((t) => `\tTopic${pascal(t.name)},`).join("\n") + "\n}\n");

// Go KYC findings
write("go/pkg/events/kyc_gen.go",
  HDR + "package events\n\n// KYC finding codes and routes.\nconst (\n" +
  kyc.findings.map((f) => `\tFinding${pascal(f.code.toLowerCase())} = "${f.code}"`).join("\n") + "\n)\n\nconst (\n" +
  kyc.routes.map((r) => `\tRoute${pascal(r)} = "${r}"`).join("\n") + "\n)\n\n" +
  "// DefaultRoute maps a finding code to its default route.\nvar DefaultRoute = map[string]string{\n" +
  kyc.findings.map((f) => `\tFinding${pascal(f.code.toLowerCase())}: Route${pascal(f.route)},`).join("\n") + "\n}\n");

// TS topics
write("ts/packages/shared/src/topics.ts",
  HDR + "export const TOPICS = {\n" + topics.map((t) => `  ${upper(t.name)}: "${t.name}",`).join("\n") +
  "\n} as const;\n\nexport type Topic = (typeof TOPICS)[keyof typeof TOPICS];\n");

// TS KYC findings
write("ts/packages/shared/src/kyc-findings.ts",
  HDR + `export const KYC_ROUTES = ${JSON.stringify(kyc.routes)} as const;\nexport type KycRoute = (typeof KYC_ROUTES)[number];\n\n` +
  `export const KYC_SEVERITIES = ${JSON.stringify(kyc.severities)} as const;\nexport type KycSeverity = (typeof KYC_SEVERITIES)[number];\n\n` +
  `export const KYC_DOCUMENT_TYPES = ${JSON.stringify(kyc.documentTypes)} as const;\nexport type KycDocumentType = (typeof KYC_DOCUMENT_TYPES)[number];\n\n` +
  "export const KYC_FINDINGS = {\n" +
  kyc.findings.map((f) => `  ${f.code}: { severity: "${f.severity}", route: "${f.route}", description: ${JSON.stringify(f.description)} },`).join("\n") +
  "\n} as const;\n\nexport type KycFindingCode = keyof typeof KYC_FINDINGS;\n");
